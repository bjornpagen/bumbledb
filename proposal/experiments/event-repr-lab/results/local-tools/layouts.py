"""Compare internal coordinate layouts without merging unlike benchmark cases."""
from pathlib import Path
import argparse
import collections
import json
import statistics

from run import CANDIDATES, RESULTS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('inputs', nargs='+', help='Retained JSON files in results/')
    ap.add_argument('--output', default='LAYOUT-MEASUREMENTS.md')
    ap.add_argument('--packed-map', choices=['local', 'recursive'], default='local')
    args = ap.parse_args()
    layouts = ['face-major', 'bit-major', 'pair-major']
    buckets = collections.defaultdict(list)
    builds = set()
    out = ['# Coordinate-layout measurements', '',
           'Generated by `layouts.py`. Every cell is the median of process medians;',
           'processes receive equal weight. No fastest-run selection. Different layouts',
           'describe the same finite worlds, inputs and checked answers. Finite containers',
           'ignore the internal diagram order and act as repeated controls.', '',
           'Times include actual Free Join, grouped Event algebra and exact output counts.',
           'Fresh arenas retain imported inputs; warm arenas replay the identical query.',
           'The common outer memo is separate from recursive diagram caches, which remain active.',
           'Memory is an arena estimate including retained intermediates and caches, not peak RSS.', '',
           'Inputs: ' + ', '.join(f'[{p}](results/{p})' for p in args.inputs) + '.', '']
    for filename in args.inputs:
        data = json.loads((RESULTS / filename).read_text())
        builds.add(data['build_metadata']['binary_sha256'])
        out.append(f"- `{filename}`: {dict(collections.Counter(r['status'] for r in data['runs']))}; {data['trials']} samples per timed case.")
        for run in data['runs']:
            if run['status'] != 'passed':
                continue
            for row in run['rows']:
                if row['kind'] not in ['relations_free_join', 'modal_free_join']:
                    continue
                if row['kind'] == 'relations_free_join' and row['candidate'].startswith('packed') and row.get('packed_map', 'recursive') != args.packed_map:
                    continue
                key = (row['kind'], row['bits'], row['memo'], row['candidate'], row.get('layout', 'face-major'))
                buckets[key].append(row)
    if len(builds) != 1:
        raise SystemExit('Layout comparison requires one matched binary; compare source revisions in separate tables.')
    out += ['', 'Binary SHA-256: `' + next(iter(builds)) + '`.',
            'Packed relation-permutation policy: `' + args.packed_map + '`.', '']

    def cell(key, field, scale):
        rows = buckets.get(key)
        if not rows:
            return '—'
        values = [statistics.median(r[field]) if isinstance(r[field], list) else r[field] for r in rows]
        return f'{statistics.median(values) * scale:.3f}'

    for kind, title in [('relations_free_join', 'Closure, converse, residual, May and Must'),
                        ('modal_free_join', 'Composition and nonvacuous Must')]:
        if not any(k[0] == kind for k in buckets):
            continue
        for bits in [12, 18]:
            for field, memo, scale, label in [
                ('fresh_s', True, 1000, 'Fresh, outer memo, ms'),
                ('fresh_s', False, 1000, 'Fresh, no outer memo, ms'),
                ('warm_s', True, 1000, 'Warm, outer memo, ms'),
                ('build_s', True, 1000, 'Input arena construction, ms'),
                ('final_bytes_est', True, 1e-6, 'Retained arena, MB'),
            ]:
                out += [f'## {title}: {bits} coordinates — {label}', '',
                        '| Candidate | ' + ' | '.join(layouts) + ' |',
                        '| --- | ---: | ---: | ---: |']
                for candidate in CANDIDATES:
                    values = [cell((kind, bits, memo, candidate, layout), field, scale) for layout in layouts]
                    out.append('| ' + candidate + ' | ' + ' | '.join(values) + ' |')
                out.append('')
    path = Path(__file__).resolve().parent / args.output
    path.write_text('\n'.join(out))
    print(path)


if __name__ == '__main__':
    main()
