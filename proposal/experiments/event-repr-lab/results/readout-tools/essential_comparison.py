"""Report matched essential-table kernels without merging algorithms or phases."""
import argparse
import json
import statistics
from prepare import LAB

ap = argparse.ArgumentParser()
ap.add_argument('inputs', nargs='+')
ap.add_argument('--output', default='ESSENTIAL-MEASUREMENTS.md')
args = ap.parse_args()
rows, statuses, builds = {}, [], set()
kinds = {'free_join', 'owned_free_join', 'law_free_join',
         'symbolic_relation_free_join', 'relations_free_join'}
for name in args.inputs:
    data = json.loads((LAB/'results'/name).read_text())
    build = data['build_metadata']['binary_sha256']
    builds.add(build)
    for run in data['runs']:
        job = run['job']
        statuses.append((name, job.get('EVENT_LAB_LANE', 'verify'),
                         job.get('EVENT_LAB_CANDIDATE', 'all'),
                         job.get('EVENT_LAB_ESSENTIAL_KERNEL', 'words'), run['status']))
        for row in run['rows']:
            if row.get('kind') not in kinds:
                continue
            assert row['verified'] and run['status'] == 'passed'
            assert row.get('essential_layout','enum') == 'enum', 'Use slab_comparison.py for slab layouts.'
            kernel = row.get('essential_kernel', 'words')
            assert kernel == job.get('EVENT_LAB_ESSENTIAL_KERNEL', 'words')
            key = (row['kind'], row.get('scenario'), row.get('shape'),
                   row.get('bits'), row.get('parameter_groups'), row.get('layout'),
                   row.get('memo'), row['candidate'], row.get('target_candidate'),
                   row.get('target_layout'), row.get('transfer_import'),
                   row.get('identity_mode'), row.get('packed_map'), kernel)
            rows[key] = (row, name)  # Latest supplied process, never fastest selection.
assert len(builds) == 1, 'Use one binary per matched comparison; report revisions separately.'

def ms(r, name):
    return f'{statistics.median(r[name])*1000:.3f}'

def span(r, name):
    return f'{min(r[name])*1000:.3f}–{max(r[name])*1000:.3f}'

def label(r):
    k = '/'+r['essential_kernel'] if r['candidate'].startswith('essential') else ''
    return r['candidate']+k

lines = ['# Essential-coordinate carriers: matched native comparison', '',
    'Generated by `essential_comparison.py`; latest supplied process per exact case.',
    'Every row uses the same native executable. All essential algorithms share',
    'the same canonical normal form and full-content interner. The derived path',
    'uses constructor certificates, normalized operation memos and a counted',
    'cardinality side array; scalar/word controls remain separate.',
    'Times are milliseconds; KB means 1,000 bytes. Spread is sample min–max.',
    'Measurements use full-content canonical identity and checked answers.',
    'See [representation](ESSENTIAL.md) and the individual lane contracts.', '',
    f'Executable SHA-256: `{next(iter(builds))}`.', '']

sections = [
    ('free_join', 'Boolean Coup query',
     'The real executor joins 1,024 triangle or 4,096 clover bindings, evaluates '
     '`A & !(B | C)`, groups by union and counts. Fresh starts from input-only '
     'arenas; warm retains nodes and caches. Construction is separate. '
     'This is an ordinary-row throughput test with a controlled join topology.',
     ['Case', 'Carrier / kernel', 'Memo', 'Build', 'Join only', 'Fresh', 'Fresh min–max', 'Warm', 'Arena KB', 'Samples']),
    ('owned_free_join', 'Owned full relation query',
     'Only 24 inputs are restored; the real query computes 80 new outputs inside '
     'the borrowed destination owner. Owned compute includes program setup, '
     'query, publication and temporary release, but excludes restoration and '
     'observation. Results survive release of input/executor/original owner. '
     'The source and destination carriers are explicit; cross-carrier rows do '
     'not measure the source carrier as the query engine. See [ownership](OWNED.md).',
     ['Bits', 'Source / kernel → destination', 'Target order', 'Owner setup', 'Restore', 'Program setup', 'Query', 'Owned compute', 'Compute min–max', 'Arena KB', 'Samples']),
    ('law_free_join', 'Full relation query and exact shared-parameter observation',
     'The same 80 outputs are intersected with evidence and observed under '
     'shared Beta, fixed and zero-endpoint laws. Fresh includes algebra, '
     'coefficient contraction and exact rational evaluation. Observation plans '
     'are prepared before timing. Phase medians need not sum to the total. '
     'See [observation](OBSERVATION.md).',
     ['Bits / groups', 'Carrier / kernel', 'Memo', 'Fresh', 'Fresh min–max', 'Algebra', 'Contract', 'Evaluate', 'Warm', 'Arena KB', 'Plans + laws KB', 'Samples']),
    ('symbolic_relation_free_join', 'Full symbolic successor-chain relation query',
     'Three ordinary rows produce one real joined binding. The five outputs '
     'include full closure, converse, residual, eventual May and one-step Must. '
     'All are checked analytically; the fixture enumerates no worlds. Fresh '
     'input construction and owned computation are separate. Counts, packet '
     'encoding and oracle work are outside the timer. This is a symbolic '
     'capability test, not a join throughput test. See [diagonal](DIAGONAL.md).',
     ['Bits / states per face', 'Carrier / kernel', 'Input', 'Program setup', 'Query', 'Owned compute', 'Compute min–max', 'Arena KB', 'Packet bytes', 'Samples']),
    ('relations_free_join', 'Finite full relation query',
     'The query computes all 80 closure/converse/residual/modal outputs and '
     'their counts. Prepared identity and inputs are construction work. '
     'Warm retains graph and operation caches.',
     ['Bits', 'Carrier / kernel', 'Memo', 'Build', 'Fresh', 'Fresh min–max', 'Warm', 'Arena KB', 'Samples']),
]
for kind, title, note, columns in sections:
    selected = [r for r, _ in rows.values() if r['kind'] == kind]
    if not selected:
        continue
    selected.sort(key=lambda r: (r.get('scenario',''), r.get('bits',0),
                   r.get('parameter_groups',0), r.get('shape',''),
                   r.get('memo',False), r['candidate'], r.get('essential_kernel',''),
                   r.get('target_candidate',''), r.get('target_layout','')))
    lines += ['## '+title, '', note, '', '| '+' | '.join(columns)+' |',
              '| '+' | '.join(['---']*len(columns))+' |']
    for r in selected:
        memo = 'on' if r.get('memo') else 'off'
        if kind == 'free_join':
            cells = [r['scenario']+'/'+r['shape'], label(r), memo,
                ms(r,'build_s'), ms(r,'join_only_s'), ms(r,'fresh_s'),
                span(r,'fresh_s'), ms(r,'warm_s'), f'{r["final_bytes_est"]/1000:.1f}', len(r['fresh_s'])]
        elif kind == 'owned_free_join':
            assert r['input_roots'] == 24 and r['output_roots'] == 80
            assert min(r['novel_publication_classes']) > 0
            cells = [r['bits'], label(r)+' → '+r['target_candidate'], r['target_layout'],
                *[ms(r,k) for k in ['target_setup_s','restore_inputs_s','program_setup_s','query_s','owned_compute_s']],
                span(r,'owned_compute_s'), f'{r["final_arena_bytes_est"]/1000:.1f}', len(r['owned_compute_s'])]
        elif kind == 'law_free_join':
            cells = [f'{r["bits"]} / {r["parameter_groups"]}', label(r), memo,
                ms(r,'fresh_s'), span(r,'fresh_s'),
                *[ms(r,k) for k in ['algebra_s','contraction_s','evaluation_s','warm_s']],
                f'{r["final_bytes_est"]/1000:.1f}',
                f'{(r["observation_plan_bytes_est"]+r["law_bytes_est"])/1000:.1f}', len(r['fresh_s'])]
        elif kind == 'symbolic_relation_free_join':
            assert r['new_classes'] > 0
            cells = [f'{r["bits"]} / {r["states"]:,}', label(r),
                *[ms(r,k) for k in ['input_s','program_setup_s','query_s','owned_compute_s']],
                span(r,'owned_compute_s'), f'{r["final_arena_bytes_est"]/1000:.1f}',
                r['output_packet_bytes'], len(r['owned_compute_s'])]
        else:
            cells = [r['bits'], label(r), memo, ms(r,'build_s'), ms(r,'fresh_s'),
                span(r,'fresh_s'), ms(r,'warm_s'), f'{r["final_bytes_est"]/1000:.1f}', len(r['fresh_s'])]
        assert len(cells) == len(columns)
        lines.append('| '+' | '.join(map(str,cells))+' |')
    lines.append('')
lines += ['## Process outcomes', '', '| Evidence | Lane | Carrier | Essential kernel | Status |',
          '| --- | --- | --- | --- | --- |']
for name, lane, candidate, kernel, status in statuses:
    lines.append(f'| [raw](results/{name}) | {lane} | {candidate} | {kernel} | {status} |')
lines.append('')
(LAB/args.output).write_text('\n'.join(lines))
print(f'Wrote {args.output}: {len(rows)} completed cases, {len(statuses)} processes.')
