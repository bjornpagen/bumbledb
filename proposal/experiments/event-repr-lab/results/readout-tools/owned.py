"""Report native queries that publish new roots into the borrowed retained owner."""
import argparse
import json
import statistics
from prepare import LAB

ap = argparse.ArgumentParser()
ap.add_argument('inputs', nargs='+')
ap.add_argument('--output', default='OWNED-MEASUREMENTS.md')
args = ap.parse_args()
rows, statuses = {}, []
for name in args.inputs:
    for run in json.loads((LAB/'results'/name).read_text())['runs']:
        if run['job'].get('EVENT_LAB_LANE') != 'owned': continue
        statuses.append((name, run['job']['EVENT_LAB_CANDIDATE'], run['status']))
        for r in run['rows']:
            if r.get('kind') != 'owned_free_join': continue
            assert r['verified'] and min(r['novel_publication_classes']) > 0
            assert r['input_roots'] == 24 and r['output_roots'] == 80
            key = (r['bits'], r['layout'], r['candidate'], r['target_candidate'], r['target_layout'], r['transfer_import'], r.get('identity_mode','legacy-table'))
            rows[key] = r

def ms(values): return 1000 * statistics.median(values)

lines = ['# Native queries with retained result ownership', '',
         'Generated by `owned.py`; latest supplied process for each case.',
         'Times are milliseconds and KB means 1,000 bytes. Only the 24 input',
         'roots are imported. The query computes and publishes 80 result roots',
         'inside the actual target owner, using a mutable borrow and no carrier',
         'clone. Owned compute includes the owner lock, program setup, Free Join,',
         'algebra, publication and release of temporary program state.',
         'Program setup constructs identity and validates the product/maps. The',
         'identity column names its constructor; legacy-table predates the explicit',
         'full-product cardinality check. Compare algorithms within one binary.',
         'Query excludes cardinality/law observation. Owner setup uses the',
         'fixture\'s unconstrained binary-product constructor. Input restoration',
         'includes a fresh support-map proof. Source construction/export, strict',
         'packet decode, native engine preparation, independent oracle construction',
         'and result comparisons are outside those timed phases.',
         'The result is checked again after dropping the native executor, input',
         'batch and original scope variable; its batch must be the sole owner.',
         'Novel classes count complementary pairs for one-bit carriers and',
         'individual roots for bdd-root; they are not a cross-carrier Event count.',
         'Arena estimates omit allocator and owner/registry overhead.',
         'See [contract](OWNED.md).', '']
for case in sorted({key[:2] for key in rows}):
    lines += [f'## {case[0]} coordinates, source {case[1]}', '',
              '| Source → target | Target order | Import | Identity | Owner setup | Restore inputs | Program setup | Query | Owned compute | Compute min–max | New classes | Arena KB | Samples |',
              '| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for key in sorted(k for k in rows if k[:2] == case):
        r = rows[key]
        values = ' | '.join(f'{ms(r[k]):.3f}' for k in ['target_setup_s','restore_inputs_s','program_setup_s','query_s','owned_compute_s'])
        total = r['owned_compute_s']
        new = r['novel_publication_classes']
        lines.append(f'| {r["candidate"]} → {r["target_candidate"]} | {r["target_layout"]} | {r["transfer_import"]} | {r.get("identity_mode","legacy-table")} | {values} | {min(total)*1000:.3f}–{max(total)*1000:.3f} | {min(new)}–{max(new)} | {r["final_arena_bytes_est"]/1000:.1f} | {len(total)} |')
    lines.append('')
lines += ['## Process outcomes', '', '| Evidence | Source | Status |', '| --- | --- | --- |']
for name, candidate, status in statuses:
    lines.append(f'| [raw](results/{name}) | {candidate} | {status} |')
lines.append('')
(LAB/args.output).write_text('\n'.join(lines))
print(f'Wrote {args.output}: {len(rows)} completed cases, {len(statuses)} processes.')
