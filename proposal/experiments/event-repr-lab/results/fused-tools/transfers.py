"""Report checked transport phases separately from resident Free Join work."""
import argparse
import json
import statistics
from prepare import LAB

ap = argparse.ArgumentParser()
ap.add_argument('inputs', nargs='+')
ap.add_argument('--output', default='TRANSPORT-MEASUREMENTS.md')
args = ap.parse_args()
rows, statuses, fingerprints = {}, [], {}
phases = ('encode_s', 'decode_s', 'target_setup_s', 'restore_s')
for name in args.inputs:
    data = json.loads((LAB/'results'/name).read_text())
    for run in data['runs']:
        if run['job'].get('EVENT_LAB_LANE') != 'transport':
            continue
        statuses.append((name, run['job']['EVENT_LAB_CANDIDATE'], run['status']))
        for row in run['rows']:
            if row.get('kind') != 'transfer_free_join':
                continue
            assert row['verified']
            assert len({len(row[k]) for k in ('query_s', *phases)}) == 1
            key = (row['bits'], row['layout'], row['candidate'],
                   row['target_candidate'], row['target_layout'],
                   row.get('transfer_import', 'recursive'),
                   row.get('transfer_setup', 'fixture'))
            # A timeout can retain already completed, independently verified rows.
            rows[key] = (row, name, run['status'])
            target = (row['bits'], row['target_candidate'], row['target_layout'])
            value = (row['canonical_packet_bytes'], row['canonical_packet_hash'])
            assert fingerprints.setdefault(target, value) == value, target

def ms(samples):
    return 1000 * statistics.median(samples)

lines = [
    '# Checked Event transport after Free Join', '',
    'Generated by `transfers.py`; latest supplied process per case, without',
    'selecting the fastest run. Times are milliseconds; KB means 1,000 bytes.',
    'Source query: actual Free Join, grouped relations, closure, converse, residual,',
    'May and Must. It excludes cardinality/law observation. Each packet has 24 input roots and',
    '80 output roots. Encode includes graph export; decode validates the packet.',
    'Setup constructs a fresh target scope, either from the fixture support',
    'bitset or the declared full-product constructor (explicit setup column). Restore',
    'includes a full-product support-map proof, canonical import and publication.',
    'Transfer total is the median of paired phase sums, excluding source query.',
    'Destination query replay, independent bitset comparisons and full canonical',
    'byte comparisons are outside timing. Initial source input/engine preparation',
    'and source-arena cloning are outside timing. Setup includes presentation',
    'construction cost; it is not just owner allocation. No disk I/O is measured.',
    'The import column distinguishes recursive rebuilding, direct table',
    'construction, and words: axis permutation followed by whole-word graph',
    'construction/local broadcast. Unsupported shapes retain exact recursive',
    'fallback. All modes retain the same',
    'support checks and canonical identities. Direct import never moves a',
    'complement outside existential elimination.',
    'Arena estimates include retained imported intermediates but omit allocator',
    'overhead and transient proof-arena peak memory. See [contract](TRANSPORT.md).', '',
]
for case in sorted({key[:2] for key in rows}):
    bits, layout = case
    lines += [f'## {bits} coordinates, source {layout}', '',
              '| Source → destination | Destination order | Import | Setup kind | Query | Encode | Decode | Setup | Restore | Transfer total | Total min–max | Packet KB | Target arena KB | Samples |',
              '| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for key in sorted(k for k in rows if k[:2] == case):
        row, _, _ = rows[key]
        total = [sum(parts) for parts in zip(*(row[k] for k in phases))]
        values = ' | '.join(f'{ms(row[k]):.3f}' for k in ('query_s', *phases))
        lines.append(f"| {row['candidate']} → {row['target_candidate']} | {row['target_layout']} | {key[5]} | {key[6]} | {values} | {ms(total):.3f} | {1000*min(total):.3f}–{1000*max(total):.3f} | {row['packet_bytes']/1000:.3f} | {row['target_bytes_est']/1000:.1f} | {len(total)} |")
    lines.append('')

lines += ['## Common packed512 destination', '',
          'The native assertions compare complete destination bytes with an arena',
          'built independently from fixture bitsets. The generator additionally',
          'checks matching byte lengths and reporting fingerprints across sources.',
          'A fingerprint alone is never the equality proof. This is canonicality',
          'for the fixed carrier, order, named finite space and ordered root batch;',
          'it does not establish representation-independent source packets or a',
          'per-Event persistent fact identity protocol.', '',
          '| Coordinates | Source order | Sources verified | Destination bytes |',
          '| ---: | --- | ---: | ---: |']
for case in sorted({key[:2] for key in rows}):
    selected = [row for key, (row, _, _) in rows.items()
                if key[:2] == case and key[3:5] == ('packed512', 'bit-major')]
    if selected:
        assert len({r['canonical_packet_bytes'] for r in selected}) == 1
        lines.append(f'| {case[0]} | {case[1]} | {len({r["candidate"] for r in selected})} | {selected[0]["canonical_packet_bytes"]} |')
lines += ['', '## Process outcomes', '',
          'Completed rows from capped/timed-out processes, if any, remain visible;',
          'missing later rows are not counted as successes or zero-duration work.', '',
          '| Evidence | Source candidate | Process status |', '| --- | --- | --- |']
for name, candidate, status in statuses:
    lines.append(f'| [raw](results/{name}) | {candidate} | {status} |')
lines.append('')
(LAB/args.output).write_text('\n'.join(lines))
print(f'Wrote {args.output}: {len(rows)} completed cases, {len(statuses)} processes.')
