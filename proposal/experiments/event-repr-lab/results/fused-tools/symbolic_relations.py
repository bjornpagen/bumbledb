"""Report full symbolic counter queries through the real native executor."""
import argparse, json, statistics
from prepare import LAB

ap = argparse.ArgumentParser()
ap.add_argument('inputs', nargs='+')
ap.add_argument('--output', default='SYMBOLIC-RELATION-MEASUREMENTS.md')
args = ap.parse_args()
rows, statuses = {}, []
for name in args.inputs:
    data = json.loads((LAB/'results'/name).read_text())
    for run in data['runs']:
        if run['job'].get('EVENT_LAB_LANE') != 'symbolic-relations': continue
        statuses.append((name, run['job']['EVENT_LAB_CANDIDATE'], run['status']))
        for row in run['rows']:
            if row.get('kind') != 'symbolic_relation_free_join': continue
            assert row['verified'] and row['new_classes'] > 0
            rows[row['bits'], row['candidate'], row['identity_mode']] = row

def ms(values): return statistics.median(values)*1000

lines = ['# Full symbolic counter queries through Free Join', '',
    'Generated by `symbolic_relations.py`; latest supplied process per case.',
    'Times are milliseconds; KB means 1,000 bytes. The fixture contains three',
    'ordinary rows and one joined binding. Its computed stage returns five Events:',
    'full reflexive/transitive closure, converse, a residual, eventual May and',
    'one-step Must. Coordinate order is bit-major. The relation program retains',
    'common operation memos; every sample constructs a fresh owner and inputs.',
    'Input construction and owned computation are separate. Owned computation',
    'includes locking, program preparation, the full query, publication and',
    'release of temporary program state. Native image/executor preparation,',
    'analytical oracle construction, byte comparison, counts and output encoding',
    'are outside both timed phases. Memory estimates omit allocator and owner',
    'registry overhead. There is no world enumeration in the symbolic fixture.',
    'This tests symbolic capability; one binding is not a join throughput test.',
    'See [construction and oracle](DIAGONAL.md).', '']
for bits in sorted({key[0] for key in rows}):
    lines += [f'## {bits} coordinates, {1 << (bits//3):,} states per face', '',
        '| Carrier | Identity | Input construction | Program setup | Query | Owned compute | Compute min–max | Iterations | Arena KB | Packet bytes | Samples |',
        '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for key in sorted(k for k in rows if k[0] == bits):
        r = rows[key]
        values = ' | '.join(f'{ms(r[k]):.3f}' for k in ['input_s','program_setup_s','query_s','owned_compute_s'])
        samples = r['owned_compute_s']
        steps = r['iterations']
        lines.append(f'| {r["candidate"]} | {r["identity_mode"]} | {values} | {min(samples)*1000:.3f}–{max(samples)*1000:.3f} | {min(steps)}–{max(steps)} | {r["final_arena_bytes_est"]/1000:.1f} | {r["output_packet_bytes"]} | {len(samples)} |')
    lines.append('')
lines += ['## Process outcomes', '', '| Evidence | Carrier | Status |', '| --- | --- | --- |']
for name, candidate, status in statuses:
    lines.append(f'| [raw](results/{name}) | {candidate} | {status} |')
lines.append('')
(LAB/args.output).write_text('\n'.join(lines))
print(f'Wrote {args.output}: {len(rows)} completed cases, {len(statuses)} processes.')
