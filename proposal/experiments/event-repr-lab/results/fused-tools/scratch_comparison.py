"""Compare allocation strategies without merging result or storage contracts."""
from pathlib import Path
import argparse, hashlib, json, statistics
from words_comparison import LAB, KEYS, load_rows

def collect(inputs):
    rows,processes,binary = load_rows(inputs, kernels=('scalar','words','scratch'))
    pairs=[]
    for key,(scratch,source) in rows.items():
        if scratch['occupancy_kernel'] != 'scratch' or scratch['classifier'] != 'direct': continue
        words,word_source = rows[key[:-1]+('words',)]
        for field in ['input_storage','final_storage','input_nodes','final_nodes',
                      'input_bytes_est','final_bytes_est','signature_cache_entries','signature_cache_bytes_est']:
            assert scratch[field] == words[field],(key,field)
        phases = {phase:dict(
            words_median_s=statistics.median(words[phase]),scratch_median_s=statistics.median(scratch[phase]),
            words_over_scratch=statistics.median(words[phase])/statistics.median(scratch[phase]),
            words_min_s=min(words[phase]),words_max_s=max(words[phase]),
            scratch_min_s=min(scratch[phase]),scratch_max_s=max(scratch[phase]),
            words_samples=len(words[phase]),scratch_samples=len(scratch[phase]))
            for phase in ['fresh_s','warm_s','join_only_s']}
        pairs.append(dict(case=dict(zip(KEYS,key)),word_source=word_source,scratch_source=source,
                          phases=phases,carrier_bytes_est=scratch['final_bytes_est'],
                          carrier_nodes=scratch['final_nodes'],signature_cache_entries=scratch['signature_cache_entries']))
    return rows,processes,binary,pairs

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('inputs',nargs='+')
    ap.add_argument('--output',default='SCRATCH-MEASUREMENTS.md')
    ap.add_argument('--record',default='scratch-comparison.json')
    args=ap.parse_args()
    rows,processes,binary,pairs=collect(args.inputs)
    result=dict(passed=True,inputs=args.inputs,binary_sha256=binary,cases=len(rows),
                matched_kernel_cases=len(pairs),processes=processes,pairs=pairs,
                checker_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                row_checker_sha256=hashlib.sha256((LAB/'words_comparison.py').read_bytes()).hexdigest(),
                rule='Latest supplied process per exact case, never fastest selection. Exact histogram and survivor counts match all modes.')
    (LAB/'results'/args.record).write_text(json.dumps(result,indent=2)+'\n')
    lines=['# Bounded alignment scratch through Free Join','',
        'Generated by `scratch_comparison.py`. One executable; latest supplied',
        'process per exact case, without fastest-process selection. Milliseconds;',
        'KB means 1,000 bytes. Complete signature histograms and every grouped',
        'survivor count are checked. Scope lock, input validation, actual join,',
        'classification, predicate filtering and counts are timed. Construction,',
        'cloning, native setup, publication, checking and release are outside.',
        'Both direct kernels preserve identical resident arenas and pair caches.',
        'Scratch avoids alignment allocations but still allocates a traversal memo.',
        'Its one workspace per classification is 32 bytes at K=6 or 256 at K=9;',
        'compiler frames and traversal storage are additional. Resident estimates',
        'exclude temporary storage. Ordered cuts have no signature-15 pairs.',
        'See [the implementation and limits](SCRATCH.md).','',
        f'Executable SHA-256: `{binary}`.','']
    groups=sorted({tuple(r[k] for k in KEYS[:4]) for r,_ in rows.values()})
    for scenario,shape,predicate,memo in groups:
        selected=[r for r,_ in rows.values() if tuple(r[k] for k in KEYS[:4])==(scenario,shape,predicate,memo)]
        sample=selected[0]
        lines += [f'## {scenario}, {shape}, {predicate}, pair memo {"on" if memo else "off"}','',
                  f'{sample["accepted"]:,} / {sample["rows"]:,} bindings survive; {sample["histogram"][15]:,} have signature 15.','',
                  '| Carrier / layout | Algorithm | Join only | Fresh | Fresh min–max | Warm | Input KB | Added resident KB | Pair cache KB | Samples |',
                  '| --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: |']
        for r in sorted(selected,key=lambda r:(r['candidate'],r['essential_layout'],r['classifier'],r['occupancy_kernel'])):
            label=r['candidate']+('/'+r['essential_layout'] if r['candidate'].startswith('essential') else '')
            algorithm=r['classifier']+('/'+r['occupancy_kernel'] if r['classifier']=='direct' and r['candidate'].startswith('essential') else '')
            cells=[label,algorithm,f'{statistics.median(r["join_only_s"])*1000:.3f}',
                   f'{statistics.median(r["fresh_s"])*1000:.3f}',
                   f'{min(r["fresh_s"])*1000:.3f}–{max(r["fresh_s"])*1000:.3f}',
                   f'{statistics.median(r["warm_s"])*1000:.3f}',
                   f'{r["input_bytes_est"]/1000:.1f}',f'{(r["final_bytes_est"]-r["input_bytes_est"])/1000:.1f}',
                   f'{r["signature_cache_bytes_est"]/1000:.1f}',str(len(r['fresh_s']))]
            lines.append('| '+' | '.join(cells)+' |')
        lines.append('')
    lines += ['## Evidence','',f'{len(rows)} cases, {len(pairs)} matched kernel pairs, {len(processes)} serial processes.','']
    lines += [f'- [Raw samples and logs](results/{name}).' for name in args.inputs]
    (LAB/args.output).write_text('\n'.join(lines)+'\n')
    print(f'Wrote {args.output}: {len(rows)} cases; {len(pairs)} allocated/scratch pairs.')

if __name__=='__main__': main()
