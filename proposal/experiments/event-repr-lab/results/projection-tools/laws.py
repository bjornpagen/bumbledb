"""Summarize exact law timings; retain failed/capped jobs and sample spread."""
from pathlib import Path
import argparse, json, statistics
from prepare import LAB

ap = argparse.ArgumentParser()
ap.add_argument('inputs', nargs='+')
ap.add_argument('--output', default='LAW-MEASUREMENTS.md')
args = ap.parse_args()
rows, statuses = {}, []
for name in args.inputs:
    data = json.loads((LAB/'results'/name).read_text())
    for run in data['runs']:
        if run['job'].get('verify'): continue
        statuses.append((name, run['job'].get('EVENT_LAB_CANDIDATE'), run['status']))
        for row in run['rows']:
            if row.get('kind') != 'law_free_join': continue
            assert row['verified'] and run['status'] == 'passed'
            key = (row['bits'], row['parameter_groups'], row['layout'], row['memo'], row['candidate'])
            rows[key] = (row, name)  # Latest supplied run, never the fastest selection.

def ms(xs): return statistics.median(xs)*1000
lines = [
    '# Exact law observations through Free Join', '',
    'Generated by `laws.py`; latest supplied process for each case. Times are',
    'milliseconds. Every candidate returns the same 80 evidence-intersected events',
    'and 240 exact conditional observations (including 80 undefined at the zero endpoint).',
    'Fresh arenas begin with inputs; prepared coefficient masks and law plans persist.',
    'Construction, region-export verification and fixture oracle are outside query timing.',
    'Algebra includes the real join, closure, converse, residuals and modal outputs.',
    'Per-phase medians need not sum to the median total. Warm figures retain algebra',
    'nodes/caches; observation traversal memos are fresh. Memory columns separate',
    'retained Event arena from observation plans/laws; neither includes transient',
    'traversal-memo peak memory or allocator overhead. See [contract](OBSERVATION.md).', '',
]
for case in sorted(set(key[:4] for key in rows)):
    bits, groups, layout, memo = case
    lines += [f'## {bits} coordinates, {groups} parameter groups, {layout}, outer memo {"on" if memo else "off"}', '',
              '| Candidate | Fresh median | Fresh min–max | Algebra | Contract | Evaluate | Warm | Event KB | Plans + laws KB | Samples |',
              '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    selected = [(k, v) for k, v in rows.items() if k[:4] == case]
    for key, (row, name) in sorted(selected, key=lambda kv: ms(kv[1][0]['fresh_s'])):
        lo, hi = min(row['fresh_s'])*1000, max(row['fresh_s'])*1000
        plans = row['observation_plan_bytes_est'] + row['law_bytes_est']
        lines.append(f"| {row['candidate']} | {ms(row['fresh_s']):.3f} | {lo:.3f}–{hi:.3f} | {ms(row['algebra_s']):.3f} | {ms(row['contraction_s']):.3f} | {ms(row['evaluation_s']):.3f} | {ms(row['warm_s']):.3f} | {row['final_bytes_est']/1000:.1f} | {plans/1000:.1f} | {len(row['fresh_s'])} |")
    lines.append('')

lines += ['## Retained process outcomes', '', '| File | Candidate | Status |', '| --- | --- | --- |']
for name, candidate, status in statuses:
    lines.append(f'| [raw](results/{name}) | {candidate} | {status} |')
lines.append('')
if rows:
    row, name = next(iter(rows.values()))
    lines += ['## Exact example outputs', '',
              'The first five outputs of one retained process, under its Beta law and',
              f'plug-in mean; {row["bits"]} coordinates, {row["parameter_groups"]} groups, [raw](results/{name}).', '',
              '| Output | Shared Beta law | Plug-in mean |', '| --- | --- | --- |']
    for i, (a, b) in enumerate(zip(row['examples_beta'], row['examples_mean'])):
        lines.append(f'| {i} | `{a}` | `{b}` |')
    lines.append('')
(LAB/args.output).write_text('\n'.join(lines))
print(f'Wrote {args.output}: {len(rows)} measured cases, {len(statuses)} process outcomes.')
