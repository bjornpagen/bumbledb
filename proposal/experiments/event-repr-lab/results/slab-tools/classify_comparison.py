"""Keep classifier algorithms, pair-memo modes and predicate selectivity distinct."""
import argparse, json, statistics
from prepare import LAB

ap = argparse.ArgumentParser()
ap.add_argument('inputs',nargs='+')
ap.add_argument('--output',default='CLASSIFY-MEASUREMENTS.md')
args = ap.parse_args()
rows, statuses, builds = {}, [], set()
for name in args.inputs:
    data = json.loads((LAB/'results'/name).read_text())
    builds.add(data['build_metadata']['binary_sha256'])
    for run in data['runs']:
        job = run['job']
        statuses.append((name,job.get('EVENT_LAB_CANDIDATE','verify'),job.get('EVENT_LAB_SCENARIO',''),job.get('EVENT_LAB_CLASSIFY',''),run['status']))
        if run['status'] != 'passed':
            continue  # Preserve the outcome; incomplete processes supply no timing rows.
        for r in run['rows']:
            if r.get('kind') != 'signature_free_join': continue
            assert run['status']=='passed' and r['verified']
            assert sum(r['histogram']) == r['rows'] and r['histogram'][0] == 0
            assert 0 < r['accepted'] < r['rows']
            if r['classifier']=='direct':
                assert r['input_nodes']==r['final_nodes'] and r['input_bytes_est']==r['final_bytes_est']
            assert r.get('essential_layout','enum') == 'enum', 'Use slab_comparison.py for slab layouts.'
            key = (r['scenario'],r['shape'],r['predicate'],r['memo'],r['candidate'],r['classifier'],r['essential_kernel'])
            rows[key] = r
assert len(builds)==1, 'Separate executable revisions in separate comparisons.'
def ms(r,key): return statistics.median(r[key])*1000
lines = ['# Scoped relationship filtering through Free Join','',
    'Generated by `classify_comparison.py`; latest supplied process per exact case.',
    'Times are milliseconds; KB means 1,000 bytes. Every row uses one executable.',
    'Only inputs are imported. Timed queries lock the retained owner, resolve all',
    'input keys, run the real join, classify pairs, apply a sixteen-entry keep',
    'table and count survivors by group. The complete class histogram and every',
    'group count are checked against a per-supported-world/nested-loop oracle.',
    'Fresh starts with an input-only owner; warm retains nodes and pair memos.',
    'The join-only baseline uses the same lock/input resolution and no classifier.',
    'Input construction/cloning/publication, native setup, oracle construction,',
    'checking and owner release are outside the query timer. Native setup is',
    'retained in raw data; the other excluded work has no reported total.',
    'The direct path must leave resident nodes/bytes unchanged.',
    'Transient traversal memos and allocator/owner overhead are excluded from',
    'retained-byte estimates. Essential carriers use the derived algorithm path.',
    'This is filtering in a computed-stage sink; it does not establish planner',
    'pushdown, a batched NEON keep-table kernel or native Event schema support.',
    'See [contract and limitations](CLASSIFY.md).','',
    f'Executable SHA-256: `{next(iter(builds))}`.','']
for case in sorted({k[:4] for k in rows}):
    scenario,shape,predicate,memo = case
    selected = [r for k,r in rows.items() if k[:4]==case]
    assert len({(r['accepted'],r['rows'],tuple(r['histogram'])) for r in selected})==1
    for candidate in {r['candidate'] for r in selected}:
        assert len({(r['input_nodes'],r['input_bytes_est']) for r in selected if r['candidate']==candidate})==1
    r = selected[0]
    lines += [f'## {scenario}, {shape}, {predicate}, pair memo {"on" if memo else "off"}','',
        f'{r["accepted"]:,} of {r["rows"]:,} bindings survive ({100*r["accepted"]/r["rows"]:.1f}%).','',
        '| Carrier | Algorithm | Join only | Fresh | Fresh min–max | Warm | Input KB | Added resident KB | Pair cache KB | Cache entries | Samples |',
        '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for r in sorted(selected,key=lambda r:(r['candidate'],r['classifier'])):
        lines.append(f'| {r["candidate"]} | {r["classifier"]} | {ms(r,"join_only_s"):.3f} | {ms(r,"fresh_s"):.3f} | {min(r["fresh_s"])*1000:.3f}–{max(r["fresh_s"])*1000:.3f} | {ms(r,"warm_s"):.3f} | {r["input_bytes_est"]/1000:.1f} | {(r["final_bytes_est"]-r["input_bytes_est"])/1000:.1f} | {r["signature_cache_bytes_est"]/1000:.1f} | {r["signature_cache_entries"]} | {len(r["fresh_s"])} |')
    lines.append('')
lines += ['## Process outcomes','','| Evidence | Carrier | Scenario | Algorithm | Status |','| --- | --- | --- | --- | --- |']
for name,candidate,scenario,mode,status in statuses:
    lines.append(f'| [raw](results/{name}) | {candidate} | {scenario} | {mode} | {status} |')
lines.append('')
(LAB/args.output).write_text('\n'.join(lines))
print(f'Wrote {args.output}: {len(rows)} completed cases, {len(statuses)} processes.')
