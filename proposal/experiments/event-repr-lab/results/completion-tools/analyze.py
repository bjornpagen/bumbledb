"""Recompute compact tables from retained raw samples; no third-party packages."""
from pathlib import Path
import argparse, collections, json, statistics
from run import CANDIDATES, SCENARIOS, RESULTS

def median(row, field):
    value = row[field]
    return statistics.median(value) if isinstance(value, list) else value

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('inputs', nargs='+', help='JSON files relative to results/')
    ap.add_argument('--output', default='MEASUREMENTS.md')
    ap.add_argument('--latest', action='store_true', help='Use the last named process per case, not an average across runs')
    ap.add_argument('--layout',choices=['face-major','bit-major','pair-major'],default='face-major')
    ap.add_argument('--packed-map',choices=['local','recursive'],default='local')
    args = ap.parse_args()
    buckets = collections.defaultdict(list)
    statuses = {}
    symbolic = []
    symbolic_latest = {}
    for filename in args.inputs:
        data = json.loads((RESULTS / filename).read_text())
        statuses[filename] = dict(collections.Counter(r['status'] for r in data['runs']))
        for run in data['runs']:
            if run['status'] != 'passed': continue
            for row in run['rows']:
                assert row.get('essential_layout','enum') == 'enum', 'Use slab_comparison.py for slab layouts.'
                kind = row['kind']
                if kind == 'relations_free_join' and row['candidate'].startswith('packed') and row.get('packed_map','recursive') != args.packed_map: continue
                if kind in ['modal_free_join','relations_free_join','elimination'] and row.get('layout','face-major') != args.layout: continue
                if kind == 'free_join':
                    key = (kind, row['candidate'], row['scenario'], row['shape'], row['memo'])
                elif kind in ['modal_free_join', 'relations_free_join']:
                    key = (kind, row['candidate'], row['bits'], row['memo'])
                elif kind == 'complement':
                    key = (kind, row['candidate'], row['restricted'])
                elif kind == 'elimination':
                    key = (kind, row['candidate'], row['bits'])
                elif kind == 'symbolic':
                    if args.latest:
                        symbolic_latest[(row['candidate'],row['pairs'],row['interleaved'])] = row
                    else:
                        symbolic.append(row)
                    continue
                else: continue
                buckets[key].append(row)
                if args.latest: buckets[key] = [row]
    if args.latest:
        symbolic = list(symbolic_latest.values())
    def value(key, field, factor=1):
        rows = buckets.get(key)
        return None if not rows else statistics.median(median(r, field) for r in rows) * factor
    def fmt(x):
        return '—' if x is None else f'{x:.3f}'
    out = ['# Measured results', '',
           ('Generated by `analyze.py --latest`. Each case uses the last named process and its sample median;' if args.latest else 'Generated by `analyze.py`. Times below are medians of per-process sample medians;'),
           'each process uses seven timed samples unless its raw file says otherwise.',
           ('Earlier processes remain available in the raw inputs. This is descriptive measurement,' if args.latest else 'Separate process runs are equally weighted. This is descriptive measurement,'),
           'not a confidence interval. Memory is a structural arena estimate, not an allocation trace.', '',
           'Relational coordinate layout: `' + args.layout + '`. Finite containers retain their semantic world-bit enumeration.', '',
           'Packed relation-permutation policy: `' + args.packed_map + '`.', '',
           'Inputs: ' + ', '.join(f'[{p}](results/{p})' for p in args.inputs) + '.', '']
    for filename, counts in statuses.items(): out.append(f'- `{filename}`: {counts}')
    out += ['', '## Free Join + Event expression + grouped union + exact counts', '',
            '`fresh` resets the Event arena to imported inputs, while COLT is already built.',
            '`warm` retains regions and caches. `memo` is the common outer operator cache;',
            'diagram Apply retains its own recursive cache even with `memo=false`.', '']
    for shape in ['clover', 'triangle']:
        for field, memo in [('fresh_s',False),('fresh_s',True),('warm_s',False),('warm_s',True)]:
            out += [f'### {shape}: {field}, memo={str(memo).lower()} (milliseconds)', '',
                    '| Candidate | ' + ' | '.join(SCENARIOS) + ' |',
                    '| --- |' + ' ---: |' * len(SCENARIOS)]
            for candidate in CANDIDATES:
                values = [value(('free_join',candidate,s,shape,memo),field,1000) for s in SCENARIOS]
                out.append('| ' + candidate + ' | ' + ' | '.join(map(fmt,values)) + ' |')
            out.append('')
    out += ['### Clover constructor and retained storage', '',
            'Each cell is import milliseconds / final arena MB, with common memo enabled.', '',
            '| Candidate | ' + ' | '.join(SCENARIOS) + ' |',
            '| --- |' + ' ---: |' * len(SCENARIOS)]
    for candidate in CANDIDATES:
        cells = []
        for s in SCENARIOS:
            key = ('free_join',candidate,s,'clover',True)
            cells.append(fmt(value(key,'build_s',1000)) + ' / ' + fmt(value(key,'final_bytes_est',1e-6)))
        out.append('| ' + candidate + ' | ' + ' | '.join(cells) + ' |')
    out += ['', '## Relational Must through Free Join', '',
            '128 matched bindings; 16 groups. Compose R(X,Y) and Q(Y,Z), hide Y,',
            'compute enabledness and bad-target preimages, aggregate, then return enabled & !bad.', '',
            '| Candidate | 12-bit fresh, no memo (ms) | 18-bit fresh, no memo (ms) | 18-bit fresh, memo (ms) | 18-bit warm, memo (ms) |',
            '| --- | ---: | ---: | ---: | ---: |']
    for c in CANDIDATES:
        values = [value(('modal_free_join',c,bits,memo),field,1000) for bits,memo,field in [(12,False,'fresh_s'),(18,False,'fresh_s'),(18,True,'fresh_s'),(18,True,'warm_s')]]
        out.append('| '+c+' | '+' | '.join(map(fmt,values))+' |')
    out += ['', '## Coordinate movement, residuals and reachability through Free Join', '',
            'Group 128 bindings, then compute reflexive-transitive closure, converse,',
            'the largest admissible continuation, eventual May, and one-step Must.',
            'The result contains 80 canonical events; exact counts are timed.', '',
            '| Candidate | 12-bit fresh, no memo (ms) | 18-bit fresh, no memo (ms) | 18-bit fresh, memo (ms) | 18-bit warm, memo (ms) |',
            '| --- | ---: | ---: | ---: | ---: |']
    for c in CANDIDATES:
        values = [value(('relations_free_join',c,bits,memo),field,1000) for bits,memo,field in [(12,False,'fresh_s'),(18,False,'fresh_s'),(18,True,'fresh_s'),(18,True,'warm_s')]]
        out.append('| '+c+' | '+' | '.join(map(fmt,values))+' |')
    out += ['', '## Isolated composition / existential elimination', '',
            '| Candidate | 12-bit product + count (µs) | 18-bit product + count (µs) |',
            '| --- | ---: | ---: |']
    for c in CANDIDATES:
        out.append('| '+c+' | '+' | '.join(fmt(value(('elimination',c,b),'fresh_s',1e6)) for b in [12,18])+' |')
    out += ['', '## Explicit complement on constrained support', '',
            '48 events, 4,096 presented worlds; random support admits roughly three quarters.', '',
            '| Candidate | Import (ms) | First 48 complements (µs) | Repeated complement (ns/op) | Final arena MB |',
            '| --- | ---: | ---: | ---: | ---: |']
    for c in CANDIDATES:
        key = ('complement',c,True)
        out.append('| '+c+' | '+' | '.join(fmt(value(key,f,m)) for f,m in [('build_s',1000),('first_batch_s',1e6),('warm_per_not_s',1e9),('final_bytes_est',1e-6)])+' |')
    out += ['', '## Symbolic equality scaling', '',
            'Single construction samples, for growth intuition only. Nodes include intermediates.', '',
            '| Candidate | Bit pairs | Interleaved | Presented assignments | Arena nodes | Build (ms) |',
            '| --- | ---: | --- | ---: | ---: | ---: |']
    for r in sorted(symbolic, key=lambda r:(r['candidate'],r['pairs'],r['interleaved'])):
        out.append(f"| {r['candidate']} | {r['pairs']} | {r['interleaved']} | {r['worlds']:,} | {r['nodes']:,} | {r['build_s']*1000:.3f} |")
    out += ['', 'Resource-cap jobs are in the raw files. They are failed constructions, never fast zero-time results.', '']
    path = Path(__file__).resolve().parent / args.output
    path.write_text('\n'.join(out))
    print(path)

if __name__ == '__main__': main()
